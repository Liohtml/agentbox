// ─────────────────────────────────────────────────────────────────────────────
// Config schema. Built by cli.resolveConfig() from env + flags + defaults.
// ─────────────────────────────────────────────────────────────────────────────
export interface AgentboxConfig {
  /** Host dir mounted to CONTAINER_WORKSPACE. env: WORKSPACE (default cwd). */
  workspace: string;
  /** Host ~/.claude dir mounted read-write for credentials/config. */
  claudeDir: string;
  /** Host ~/.claude.json file (touched first so Docker mounts a file). */
  claudeJson: string;
  /** Docker image tag. */
  image: string;
  /** Docker container name (for reattach / down). */
  containerName: string;
  /** tmux session name inside the container. */
  sessionName: string;
  /** Observer web port, published host→container. Default 4317. */
  observerPort: number;
  /** Docker --memory limit, e.g. "4g". env: MEM. */
  memory: string;
  /** Docker --cpus limit, e.g. "4". env: CPUS. */
  cpus: string;
  /**
   * Optional `docker build --network` mode (e.g. "host"). Some hosts have a
   * locked-down default bridge where build steps (apt, curl, rustup) can't
   * reach the internet; `host` runs RUN steps in the host network namespace.
   * Unset → Docker's default build network. env: DOCKER_NETWORK / flag: --network.
   */
  buildNetwork?: string;
  /**
   * Launch the Claude lead with --dangerously-skip-permissions (teammates
   * inherit it). Opt-in via --yolo — the disposable, resource-capped box is
   * the environment that flag exists for, but it stays off by default.
   */
  yolo: boolean;
  /** Optional `docker run --gpus` value (e.g. "all", "device=0"). flag: --gpus. */
  gpus?: string;
  /**
   * Host ~/.gitconfig candidate path. Mounted READ-ONLY into the container
   * (git identity reuse) only if it exists at run time.
   */
  gitconfigPath: string;
  /**
   * Host ~/.config/gh candidate dir. Mounted READ-ONLY into the container
   * (gh CLI auth reuse) only if it exists at run time.
   */
  ghConfigDir: string;
  /** Path to the Dockerfile (assets/Dockerfile). */
  dockerfile: string;
  /** Build context dir for `docker build` (the assets dir). */
  buildContext: string;
  /** Host path to the bundled observer.mjs asset. */
  observerAsset: string;
  /** Host path where the generated entry script is written before mounting. */
  entryScriptPath: string;
}

